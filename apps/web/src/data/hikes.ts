const curatedIds = new Set(curatedHikes.map((hike) => hike.id))
const curatedPeakSets = new Set(
  curatedHikes.map((hike) => [...hike.peakIds].sort().join('|')),
)

/** Big enough day to pair with a camping night — not a short afternoon loop. */
export function isOvernightFriendly(hike: {
  hours: number
  distanceKm: number
  ascent: number
}) {
  return hike.hours >= 5 || hike.distanceKm >= 12 || hike.ascent >= 600
}

function withOvernightFlag<T extends Hike>(hike: T): T {
  return { ...hike, campingNight: isOvernightFriendly(hike) }
}

/** Summit-day suggestions covering list peaks, plus curated classics first. */
export const hikes: Hike[] = [
  ...curatedHikes.map((hike) =>
    withOvernightFlag({ ...hike, source: 'curated' as const }),
  ),
  ...(generatedHikes as Hike[])
    .filter((hike) => {
      if (curatedIds.has(hike.id)) return false
      const peakSet = [...hike.peakIds].sort().join('|')
      return !curatedPeakSets.has(peakSet)
    })
    .map((hike) => withOvernightFlag({ ...hike, source: 'summit' as const })),
]

export function providerLinks(hike: Hike) {
  const candidates = [hike.osMaps, hike.alternative].filter(
    (link): link is RouteLink => Boolean(link),
  )
  const allTrails =
    candidates.find(
      (link) =>
        /alltrails/i.test(link.label) || /alltrails\.com\/trail\//.test(link.url),
    ) ?? null
  const osMaps =
    candidates.find(
      (link) =>
        /os maps/i.test(link.label) || /explore\.osmaps\.com/.test(link.url),
    ) ?? null
  const other =
    candidates.find((link) => link !== allTrails && link !== osMaps) ?? null

  return {
    allTrails,
    osMaps,
    other,
    primary: allTrails ?? osMaps ?? other ?? hike.osMaps,
    alternative: other ?? osMaps ?? hike.alternative,
  }
}

export function getHikesForPeak(peakId: string): Hike[] {
  return hikes.filter((hike) => hike.peakIds.includes(peakId))
}

export function searchHikes(query: string, limit = 12): Hike[] {
  const q = query.trim().toLowerCase()
  if (q.length < 1) return []
  return hikes
    .filter((hike) => hike.name.toLowerCase().includes(q))
    .sort(
      (a, b) =>
        Number(b.name.toLowerCase().startsWith(q)) -
          Number(a.name.toLowerCase().startsWith(q)) ||
        a.name.localeCompare(b.name),
    )
    .slice(0, limit)
}
